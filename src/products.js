const getProduct = (slug) => products.find((p) => p.slug === slug);

function roadmap(slug) {
  const file = path.join(__dirname, 'roadmap', `${slug}.json`);
  if (!fs.existsSync(file)) return null;
  const r = JSON.parse(fs.readFileSync(file, 'utf8'));
  r.total = r.milestones.reduce((n, m) => n + m.total, 0);
  r.done = r.milestones.reduce((n, m) => n + m.done, 0);
  r.current = r.milestones.find((m) => m.status === 'next') || null;
  const [y, mo, d] = r.updated.split('-');
  r.updatedText = `${d}.${mo}.${y}`;
  return r;
}

